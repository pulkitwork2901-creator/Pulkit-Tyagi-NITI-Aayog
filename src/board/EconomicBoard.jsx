import './board.css';
import KpiStrip from './KpiStrip.jsx';
import MonitorTable from './MonitorTable.jsx';
import TrendChart from './TrendChart.jsx';
import useIndicators from './useIndicators.js';
import { formatDateTime, formatValue } from './format.js';

const HEADLINE = ['gdp', 'cpi', 'fx_reserves', 'inr_usd'];

function Summary({ byId }) {
  const gdp = byId.gdp;
  const cpi = byId.cpi;
  const repo = byId.repo;
  if (!gdp || !cpi) return null;
  return (
    <p className="eb-summary">
      Real GDP grew <strong>{formatValue(gdp.value, 1)}%</strong> in {gdp.period}. CPI inflation is{' '}
      <strong>{formatValue(cpi.value, 2)}%</strong> for {cpi.period}
      {repo ? <>, against a policy repo rate of <strong>{formatValue(repo.value, 2)}%</strong></> : null}.
    </p>
  );
}

function Status({ data, error, onReload }) {
  const mospi = data?.sources?.mospi;
  const stale = mospi && mospi.status !== 'ok';
  return (
    <div className="eb-status" role="status">
      <span className={`eb-status-dot ${stale ? 'eb-status-stale' : ''}`} aria-hidden="true" />
      <span>
        {stale ? 'MoSPI could not be reached, showing the last good figures.' : 'MoSPI figures up to date.'}
        <br />
        <span className="eb-muted">Refreshed {formatDateTime(data.generated_at)}</span>
        {error && <span className="eb-muted"> (latest reload failed: {error})</span>}
      </span>
      <button type="button" className="eb-btn" onClick={onReload}>Reload</button>
    </div>
  );
}

export default function EconomicBoard({ source = '/data/indicators.json', title = 'E&F-II Economic Situation Board' }) {
  const { status, data, error, reload } = useIndicators(source);

  if (status === 'loading') {
    return <div className="eb"><p className="eb-loading">Loading the latest indicators…</p></div>;
  }
  if (status === 'error' || !data) {
    return (
      <div className="eb">
        <div className="eb-error">
          <h1>The board could not load its data</h1>
          <p>{error}. Check that {source} exists and was generated by scripts/build_indicators.py.</p>
          <button type="button" className="eb-btn" onClick={reload}>Try again</button>
        </div>
      </div>
    );
  }

  const indicators = data.indicators || [];
  const byId = Object.fromEntries(indicators.map((i) => [i.id, i]));

  return (
    <div className="eb">
      <header className="eb-header">
        <div>
          <p className="eb-org">NITI Aayog, Economics and Finance II Division</p>
          <h1>{title}</h1>
          <Summary byId={byId} />
        </div>
        <Status data={data} error={error} onReload={reload} />
      </header>

      <KpiStrip indicators={indicators} ids={HEADLINE} />

      <section className="eb-section" aria-labelledby="eb-monitor">
        <div className="eb-section-head">
          <h2 id="eb-monitor">Indicator monitor</h2>
          <p>Latest official release for each indicator. A dot marks figures pulled live from MoSPI.</p>
        </div>
        <MonitorTable indicators={indicators} exclude={HEADLINE} />
      </section>

      <section className="eb-section" aria-labelledby="eb-trends">
        <div className="eb-section-head">
          <h2 id="eb-trends">Trends</h2>
          <p>Point at a bar or line for the exact figure.</p>
        </div>
        <div className="eb-charts">
          {byId.gdp && (
            <TrendChart title="Real GDP growth by quarter" note="% year on year at constant prices, 2022-23 base"
              points={byId.gdp.history} kind="bar" formatAxis={(v) => `${v}%`}
              formatTip={(v) => `${v.toFixed(1)}% real growth`} formatEnd={(v) => `${v.toFixed(1)}%`} />
          )}
          {byId.cpi && (
            <TrendChart title="CPI headline inflation by month" note="% year on year, All India combined, 2024 base"
              points={byId.cpi.history} kind="line" formatAxis={(v) => `${v}%`}
              formatTip={(v) => `${v.toFixed(2)}% inflation`} formatEnd={(v) => `${v.toFixed(2)}%`} />
          )}
        </div>
      </section>

      <footer className="eb-notes">
        <h2>About the data</h2>
        <p>GDP and CPI come from MoSPI’s official API each time the data is rebuilt. All other figures come from the team’s indicator sheet (data/manual-indicators.csv), one row per official release; the board shows the latest row for each indicator and keeps the rest as history.</p>
        <p>IIP is entered by hand because MoSPI’s API still serves the old 2011-12 base, while the official IIP moved to the 2022-23 base in June 2026. The rupee rate and 10-year G-sec yield are market closes reported in the press, not the FBIL reference rate. Changes are measured against the comparison stated in each release.</p>
      </footer>
    </div>
  );
}
