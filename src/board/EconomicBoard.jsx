import { useEffect } from 'react';
import './board.css';
import Rail from './Rail.jsx';
import useHashRoute from './useHashRoute.js';
import useIndicators from './useIndicators.js';
import { slug } from './format.js';
import IndicatorPage from './pages/IndicatorPage.jsx';
import Overview from './pages/Overview.jsx';
import SourcesPage from './pages/SourcesPage.jsx';
import ThemePage from './pages/ThemePage.jsx';

export default function EconomicBoard({ source = '/data/indicators.json', title = 'Economic Situation Board' }) {
  const { status, data, error, reload } = useIndicators(source);
  const route = useHashRoute();

  useEffect(() => {
    document.title = `${title} | NITI Aayog, E&F-II`;
  }, [title]);

  if (status === 'loading') {
    return <div className="eb eb-solo"><p className="eb-loading" role="status">Loading the latest indicators…</p></div>;
  }
  if (status === 'error' || !data) {
    return (
      <div className="eb eb-solo">
        <div className="eb-error">
          <h1>The board could not load its data</h1>
          <p>{error}. Check that {source} exists and was generated by scripts/build_indicators.py.</p>
          <button type="button" className="eb-btn" onClick={reload}>Try again</button>
        </div>
      </div>
    );
  }

  const indicators = data.indicators || [];
  const byId = Object.fromEntries(indicators.map((i) => [i.id, i]));
  const groups = [...new Set(indicators.map((i) => i.group))];
  const item = route.name === 'indicator' ? byId[route.arg] : null;
  const group = route.name === 'theme' ? groups.find((g) => slug(g) === route.arg) : null;
  const railRoute = { ...route, group: item?.group };

  let page;
  if (route.name === 'indicator') page = <IndicatorPage item={item} />;
  else if (route.name === 'theme') page = <ThemePage group={group} items={indicators.filter((i) => i.group === group)} />;
  else if (route.name === 'sources') page = <SourcesPage indicators={indicators} />;
  else page = <Overview data={data} title={title} byId={byId} groups={groups} />;

  return (
    <div className="eb">
      <div className="eb-flag" aria-hidden="true" />
      <Rail route={railRoute} groups={groups} data={data} error={error} onReload={reload} />
      <main className="eb-main" id="eb-main">{page}</main>
    </div>
  );
}
