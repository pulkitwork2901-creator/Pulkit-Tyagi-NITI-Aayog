import { useEffect, useState } from 'react';
import './board.css';
import Rail from './Rail.jsx';
import useHashRoute from './useHashRoute.js';
import useIndicators from './useIndicators.js';
import { slug } from './format.js';
import IndicatorPage from './pages/IndicatorPage.jsx';
import Dashboard from './pages/Dashboard.jsx';
import SourcesPage from './pages/SourcesPage.jsx';
import ThemePage from './pages/ThemePage.jsx';
import TradePage from './pages/TradePage.jsx';
import BalancePage from './pages/BalancePage.jsx';

// Colour schemes a viewer can pick; the choice is remembered in their browser.
export const SKINS = [
  { id: 'teal', label: 'Teal' },
  { id: 'saffron', label: 'Saffron' },
  { id: 'dark', label: 'Dark' },
];
function readSkin() {
  try {
    const s = localStorage.getItem('eb-skin');
    return SKINS.some((k) => k.id === s) ? s : 'teal';
  } catch {
    return 'teal';
  }
}

export default function EconomicBoard({ source = '/data/indicators.json', title = 'E&F-II Dashboard' }) {
  const { status, data, error, reload } = useIndicators(source);
  const route = useHashRoute();
  const [skin, setSkin] = useState(readSkin);
  const chooseSkin = (s) => {
    setSkin(s);
    try { localStorage.setItem('eb-skin', s); } catch { /* private window: keep for this visit only */ }
  };

  useEffect(() => {
    document.title = `${title} | NITI Aayog`;
  }, [title]);

  if (status === 'loading') {
    // Placeholder in the shape of the dashboard, so the page does not jump when data arrives.
    return (
      <div className="eb eb-solo eb-skel" data-skin={skin}>
        <p className="eb-sr" role="status">Loading the latest indicators…</p>
        <div className="eb-skel-hero" />
        <div className="eb-skel-row">{[0, 1, 2, 3, 4, 5].map((i) => <div key={i} className="eb-skel-tile" />)}</div>
        <div className="eb-skel-grid">{[0, 1, 2, 3, 4, 5].map((i) => <div key={i} className="eb-skel-panel" />)}</div>
      </div>
    );
  }
  if (status === 'error' || !data) {
    return (
      <div className="eb eb-solo" data-skin={skin}>
        <div className="eb-error">
          <h1>The board could not load its data</h1>
          <p>{error}. Check that {source} exists and was generated by scripts/build_indicators.py.</p>
          <button type="button" className="eb-btn" onClick={reload}>Try again</button>
        </div>
      </div>
    );
  }

  const indicators = data.indicators || [];
  const byId = Object.fromEntries(indicators.map((i) => [i.id, i]));
  const groups = [...new Set(indicators.map((i) => i.group))];
  const item = route.name === 'indicator' ? byId[route.arg] : null;
  const group = route.name === 'theme' ? groups.find((g) => slug(g) === route.arg) : null;
  const railRoute = { ...route, group: item?.group };
  const tradeBase = source.replace(/[^/]*$/, 'trade/');

  let page;
  if (route.name === 'indicator') page = <IndicatorPage item={item} />;
  else if (route.name === 'theme') page = <ThemePage group={group} items={indicators.filter((i) => i.group === group)} />;
  else if (route.name === 'sources') page = <SourcesPage indicators={indicators} />;
  else if (route.name === 'exports' || route.name === 'imports') page = <TradePage base={tradeBase} flow={route.name} view={route.arg} arg={route.arg2} />;
  else if (route.name === 'balance') page = <BalancePage base={tradeBase} />;
  else page = <Dashboard data={data} title={title} byId={byId} groups={groups} csvUrl={source.replace(/\.json$/, '.csv')} tradeBase={tradeBase} />;

  return (
    <div className="eb" data-skin={skin}>
      <div className="eb-flag" aria-hidden="true" />
      <Rail route={railRoute} groups={groups} data={data} error={error} onReload={reload} skins={SKINS} skin={skin} onSkin={chooseSkin} />
      <main className="eb-main" id="eb-main">{page}</main>
    </div>
  );
}
